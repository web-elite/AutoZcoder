const DICT = { en, fa };
let current = "en";
const listeners = new Set();

function detect() {
  const nav = String(navigator.language || "").toLowerCase();
  return nav.startsWith("fa") ? "fa" : "en";
}

export function lang() { return current; }

/** Translate a key with optional {var} interpolation. Unknown keys fall back
    to English, then to the key itself. */
export function t(key, vars) {
  const table = DICT[current] || DICT.en;
  let s = table[key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v));
  }
  return s;
}

function applyRtl(isRtl) {
  root.setAttribute("dir", isRtl ? "rtl" : "ltr");
  root.setAttribute("lang", current);
  root.classList.toggle("is-rtl", isRtl);
}

export function setLang(next, persist = true) {
  const lang = next === "fa" ? "fa" : "en";
  if (lang === current) return lang;
  current = lang;
  applyRtl(lang === "fa");
  if (persist) {
    try { localStorage.setItem(STORAGE, lang); } catch (_) { /* private mode */ }
  }
  for (const fn of [...listeners]) {
    try { fn(lang); } catch (err) { console.error(err); }
  }
  return lang;
}

export function toggle() {
  return setLang(current === "fa" ? "en" : "fa");
}

/** Subscribe to language changes; the callback receives the new lang. */
export function onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

export function init() {
  let saved = null;
  try { saved = localStorage.getItem(STORAGE); } catch (_) { /* private mode */ }
  const next = (saved === "fa" || saved === "en") ? saved : detect();
  current = next;
  applyRtl(next === "fa");
  return next;
}
